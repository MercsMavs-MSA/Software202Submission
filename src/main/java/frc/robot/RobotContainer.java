package frc.robot;

import frc.robot.Constants.OperatorConstants;
import frc.robot.commands.TeleopCommands;
import frc.robot.subsystems.arm.Arm;
import frc.robot.subsystems.arm.ArmConstants;
import frc.robot.subsystems.arm.ArmIO;
import frc.robot.subsystems.arm.ArmIOSim;
import frc.robot.subsystems.arm.ArmIOTalonFX;
import frc.robot.subsystems.arm.Arm.ArmState;
import frc.robot.subsystems.arm.ArmConstants.ArmHardware;
import edu.wpi.first.wpilibj.RobotBase;
import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.button.CommandXboxController;
import edu.wpi.first.wpilibj2.command.button.Trigger;

/**
 * This class is where the bulk of the robot should be declared. Since Command-based is a
 * "declarative" paradigm, very little robot logic should actually be handled in the {@link Robot}
 * periodic methods (other than the scheduler calls). Instead, the structure of the robot (including
 * subsystems, commands, and trigger mappings) should be declared here.
 */
public class RobotContainer {
  // The robot's subsystems and commands are defined here...
  private final Arm arm;
  private TeleopCommands teleopCommands;

  // Replace with CommandPS4Controller or CommandJoystick if needed
  private final CommandXboxController m_driverController =
      new CommandXboxController(OperatorConstants.kDriverControllerPort);

  /** The container for the robot. Contains subsystems, OI devices, and commands. */
  public RobotContainer() {
    switch (Constants.currentMode) {
      case REAL:
        arm =
          new Arm(
            new ArmIOTalonFX("rio", ArmConstants.armHardware, ArmConstants.armGains, ArmConstants.kArmMotorConfiguation, ArmConstants.kStatusSignalUpdateFrequencyHz)
          );
          break;
      case SIM:
        arm =
          new Arm(
            new ArmIOSim(0.02, ArmConstants.armHardware, ArmConstants.armSimulationConfiguration)
          );
          break;
      default:
        arm = new Arm(null);
    }

    teleopCommands = new TeleopCommands(arm);

    // Configure the trigger bindings
    configureBindings();
  }

  /**
   * Use this method to define your trigger->command mappings. Triggers can be created via the
   * {@link Trigger#Trigger(java.util.function.BooleanSupplier)} constructor with an arbitrary
   * predicate, or via the named factories in {@link
   * edu.wpi.first.wpilibj2.command.button.CommandGenericHID}'s subclasses for {@link
   * CommandXboxController Xbox}/{@link edu.wpi.first.wpilibj2.command.button.CommandPS4Controller
   * PS4} controllers or {@link edu.wpi.first.wpilibj2.command.button.CommandJoystick Flight
   * joysticks}.
   */
  private void configureBindings() {
    m_driverController.leftBumper().whileTrue(teleopCommands.armCommand(ArmState.DEPLOY_IN));
    m_driverController.rightBumper().whileTrue(teleopCommands.armCommand(ArmState.DEPLOY_OUT));
    m_driverController.y().onTrue(teleopCommands.doStuff());
  }

  /**
   * Use this to pass the autonomous command to the main {@link Robot} class.
   *
   * @return the command to run in autonomous
   */
  public Command getAutonomousCommand() {
    // An example command will be run in autonomous
    return null;
  }
}
